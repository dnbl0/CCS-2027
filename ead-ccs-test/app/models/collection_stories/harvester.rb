# frozen_string_literal: true

class CollectionStories
  # The offline harvest behind bin/rails stories:harvest. For each source it reads the story list, then each story
  # (CollectionStories::Page), and asks the matcher which records of the source's collection carry each candidate accession number.
  # A story is kept for the record pages only when at least one candidate names exactly one record; a story with no candidate,
  # whose candidates name no record (or more than one), or that a reviewer has held (Source#hold) goes to the curator list with
  # the reason. Nothing is guessed: no title or keyword matching.
  #
  #   fetch    url -> HTML, raising CollectionStories::FetchError (CollectionStories::Fetcher in the task)
  #   matcher  (collection, accession number) -> record ids (CollectionStories::SolrMatcher in the task)
  class Harvester
    Matched = Data.define(:title, :url, :image_url, :summary, :site, :collection, :accession_numbers, :record_ids, :unconfirmed)
    Unmatched = Data.define(:title, :url, :site, :collection, :candidates, :reason, :note)
    Result = Data.define(:stories, :unmatched, :errors)

    NOTES = {
      no_candidates: "No accession number in the story's image file names, captions or text.",
      no_match: "No candidate accession number names exactly one record of this collection."
    }.freeze

    def initialize(sources:, fetch:, matcher:)
      @sources = sources
      @fetch = fetch
      @matcher = matcher
    end

    def call
      stories = []
      unmatched = []
      errors = []
      @sources.each do |source|
        story_urls(source, errors).each do |url|
          entry = harvest(source, url)
          (entry.is_a?(Matched) ? stories : unmatched) << entry
        rescue FetchError => e
          errors << e.message
        end
      end
      Result.new(stories: stories, unmatched: unmatched, errors: errors)
    end

    # The data file the record pages read (config/collection_stories.yml)
    def self.yaml(result)
      data = { "stories" => result.stories.map { |story| story.to_h.transform_keys(&:to_s) },
               "unmatched" => result.unmatched.map { |story| story.to_h.transform_keys(&:to_s).merge("reason" => story.reason.to_s) } }
      <<~HEADER + data.to_yaml.delete_prefix("---\n")
        # Stories from the collection (docs/collection-stories.md). Written by bin/rails stories:harvest, then reviewed before it is
        # committed. The record page reads only "stories": a story shows on a record whose accession number AND collection match.
        # "unmatched" is the curator list: never shown on the site. To keep a story off the record pages, add its address to
        # "hold" in config/collection_story_sources.yml and harvest again; do not edit this file by hand.
      HEADER
    end

    private

    def story_urls(source, errors)
      index = Nokogiri::HTML(@fetch.call(source.index_url).to_s)
      index.css("a[href]").filter_map { |link| story_url(source, link["href"]) }.uniq
    rescue FetchError => e
      errors << e.message
      []
    end

    def story_url(source, href)
      url = Page.absolute(source.index_url, href)&.split(/[?#]/)&.first
      url if url&.start_with?(source.story_prefix) && url.length > source.story_prefix.length
    end

    def harvest(source, url)
      page = Page.parse(@fetch.call(url), url: url)
      return unmatched(source, page, :held, source.hold[url]) if source.held?(url)
      return unmatched(source, page, :no_candidates) if page.candidates.empty?

      found = page.candidates.index_with { |accession| Array(@matcher.call(source.collection, accession)) }
      confirmed = found.select { |_accession, ids| ids.size == 1 }
      return unmatched(source, page, :no_match) if confirmed.empty?

      Matched.new(title: page.title, url: url, image_url: page.image_url, summary: page.summary, site: source.name,
                  collection: source.collection, accession_numbers: confirmed.keys, record_ids: confirmed.values.flatten,
                  unconfirmed: page.candidates - confirmed.keys)
    end

    def unmatched(source, page, reason, note = NOTES[reason])
      Unmatched.new(title: page.title, url: page.url, site: source.name, collection: source.collection, candidates: page.candidates,
                    reason: reason, note: note)
    end
  end
end
